import { readFile, writeFile } from "node:fs/promises";

/**
 * Turns the vendored chart blocks into a typed registry the gallery can import.
 *
 * The blocks are plain modules with no shared index, so this walks
 * design-system/manifest.json — written by vendor-shadcn-reference.mjs — and
 * emits the imports and metadata as one file. Re-run it after vendoring.
 */
const root = new URL("../", import.meta.url);
const manifest = JSON.parse(await readFile(new URL("design-system/manifest.json", root), "utf8"));
const charts = manifest.charts ?? [];

const categories = [
  ["area", "Area Charts", "Area Chart"],
  ["bar", "Bar Charts", "Bar Chart"],
  ["line", "Line Charts", "Line Chart"],
  ["pie", "Pie Charts", "Pie Chart"],
  ["radar", "Radar Charts", "Radar Chart"],
  ["radial", "Radial Charts", "Radial Chart"],
  ["tooltip", "Tooltips", "Tooltip"],
];

const source = `// Generated by scripts/generate-chart-registry.mjs — do not edit by hand.
// Re-run it after \`node scripts/vendor-shadcn-reference.mjs\`.
import type * as React from "react";

${charts.map((c) => `import { ${c.component} } from "@/design-system/charts/${c.name}";`).join("\n")}

export type ChartCategory = ${categories.map(([id]) => `"${id}"`).join(" | ")};

export type ChartEntry = {
  name: string;
  category: ChartCategory;
  variant: string;
  description: string;
  Component: React.ComponentType;
};

export const CHART_CATEGORIES: Array<{ id: ChartCategory; label: string; singular: string }> = [
${categories.map(([id, label, singular]) => `  { id: "${id}", label: "${label}", singular: "${singular}" },`).join("\n")}
];

export const chartEntries: ChartEntry[] = [
${charts
  .map(
    (c) =>
      `  { name: "${c.name}", category: "${c.category}", variant: "${c.variant}", description: ${JSON.stringify(c.description)}, Component: ${c.component} },`
  )
  .join("\n")}
];
`;

await writeFile(new URL("app/design-system/charts/registry.ts", root), source, "utf8");
console.log(`Generated a registry for ${charts.length} chart blocks.`);
